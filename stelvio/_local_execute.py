"""Local callbacks backed by resource-creation and deployment signals."""

from __future__ import annotations

from dataclasses import make_dataclass
from functools import wraps
from pathlib import Path
from tempfile import NamedTemporaryFile
from typing import TYPE_CHECKING, Any

from pulumi import Output

from stelvio import signals
from stelvio._link_codegen import _link_names
from stelvio._signals import Handler, _current, _Receiver, _register
from stelvio.component import ComponentRegistry
from stelvio.project import get_project_root

if TYPE_CHECKING:
    from pulumi import Input

    from stelvio.app import StelvioApp
    from stelvio.signals import DeployEvent, ErrorPolicy, PhaseEvent


def _schema_source(properties: dict[str, list[str]], names: dict[str, tuple[str, str]]) -> str:
    lines = [
        "# Generated by Stelvio. Do not edit.",
        "from dataclasses import dataclass",
        "",
    ]
    for name, fields in properties.items():
        class_name, _ = names[name]
        lines.extend(
            ["", "@dataclass(frozen=True, slots=True, kw_only=True)", f"class {class_name}:"]
        )
        lines.extend(f"    {field}: str" for field in fields)
    lines.extend(
        ["", "", "@dataclass(frozen=True, slots=True, kw_only=True)", "class LocalComponents:"]
    )
    lines.extend(f"    {attribute}: {class_name}" for class_name, attribute in names.values())
    if not names:
        lines.append("    pass")
    return "\n".join(lines) + "\n"


def _write_schema(path: Path, content: str) -> None:
    with NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=path.parent, prefix=".stlv_local-", delete=False
    ) as file:
        temporary = Path(file.name)
        try:
            file.write(content)
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def _snapshot(values: dict[str, dict[str, str]], names: dict[str, tuple[str, str]]) -> object:
    components = {}
    fields = []
    for name, properties in values.items():
        class_name, attribute = names[name]
        property_type = make_dataclass(
            class_name,
            [(field, str) for field in properties],
            frozen=True,
            slots=True,
            kw_only=True,
            namespace={"__module__": "stlv_local"},
        )
        fields.append((attribute, property_type))
        components[attribute] = property_type(**properties)
    component_type = make_dataclass(
        "LocalComponents",
        fields,
        frozen=True,
        slots=True,
        kw_only=True,
        namespace={"__module__": "stlv_local"},
    )
    return component_type(**components)


async def _resolve_links(links: dict[str, dict[str, Input[str]]]) -> dict[str, dict[str, str]]:
    values = {}
    for name, properties in links.items():
        output = Output.from_input(properties)
        if not await output.is_known():
            raise ValueError(f"Local link properties for {name!r} contain unresolved values.")
        resolved = await output.future(with_unknowns=True)
        for field, value in resolved.items():
            if not isinstance(value, str):
                raise TypeError(
                    f"Local property {name!r}.{field} must resolve to a string, "
                    f"got {type(value).__name__}."
                )
        values[name] = resolved
    return values


async def _collect(event: PhaseEvent) -> None:
    session = _current.get()
    if session is None or event.command not in ("diff", "deploy"):
        return
    session.local_components = None
    links = {}
    for component in event.components:
        creator = ComponentRegistry.get_link_config_creator(type(component))
        if creator is None:
            continue
        properties = creator(component).properties
        if properties:
            if component.name in links:
                raise ValueError(f"Duplicate local link name {component.name!r}.")
            links[component.name] = dict(properties)
    schema = {name: list(properties) for name, properties in links.items()}
    names = _link_names(
        schema, class_suffix="LocalProperties", reserved_classes={"LocalComponents"}
    )
    _write_schema(get_project_root() / "stlv_local.py", _schema_source(schema, names))
    if event.command == "diff":
        return
    values = await _resolve_links(links)
    session.local_components = _snapshot(values, names)


def _register_local(app: StelvioApp, handler: Handler[Any], errors: ErrorPolicy) -> None:
    if errors not in ("fail", "continue"):
        raise ValueError("errors must be 'fail' or 'continue'")
    if not callable(handler):
        raise TypeError("local_execute handler must be callable")
    if any(existing == handler for existing in app._local_execute_handlers):  # noqa: SLF001
        return

    @wraps(handler)
    def execute(event: DeployEvent) -> object:
        if event.command != "deploy":
            return None
        session = _current.get()
        if session is None or session.local_components is None:
            raise RuntimeError(
                "Local component values were not captured during resource creation."
            )
        return handler(session.local_components)

    @wraps(handler)
    def enqueue(event: DeployEvent) -> None:
        if event.command == "deploy" and (session := _current.get()) is not None:
            session.local_callbacks.append(_Receiver(execute, errors))

    _register(app, signals.after_resource_creation, _collect, "fail")
    _register(app, signals.after_deploy, enqueue, "fail")
    app._local_execute_handlers.append(handler)  # noqa: SLF001
