def test_local_execute_resolves_bucket_properties_after_cleanup(phase_app, local_pipeline):
    phase_app.run(lambda: Bucket("my-bucket"))
    received = []
    order = []

    @phase_app.on(signals.after_deploy)
    def ordinary(event):
        order.append("signal")

    @phase_app.local_execute
    async def execute(components):
        await asyncio.sleep(0)
        assert not local_pipeline.home.file_exists("lock/demo/test.json")
        assert list((local_pipeline.root / "work").iterdir()) == []
        received.append(components)
        order.append("local")

    phase_app.local_execute(execute)
    phase_app.on(signals.after_deploy)(lambda event: order.append("last"))
    local_pipeline.commands.RichDeploymentHandler.return_value.show_completion.side_effect = (
        lambda: order.append("completion")
    )
    local_pipeline.commands.run_deploy("test")
    assert order == ["signal", "last", "completion", "local"]
    assert len(received) == 1
    assert isinstance(received[0].my_bucket.bucket_arn, str)
    assert received[0].my_bucket.bucket_arn == f"arn:aws:s3:::{received[0].my_bucket.bucket_name}"
    with raises(FrozenInstanceError, match="cannot assign"):
        received[0].my_bucket.bucket_name = "other"
    with raises(FrozenInstanceError, match="cannot assign"):
        received[0].my_bucket = None
    with raises(TypeError, match="not subscriptable"):
        received[0]["my-bucket"]
    assert set(asdict(received[0])) == {"my_bucket"}
    namespace = {}
    exec((local_pipeline.root / "stlv_local.py").read_text(), namespace)  # noqa: S102
    assert namespace["LocalComponents"].__annotations__ == {
        "my_bucket": namespace["MyBucketLocalProperties"]
    }
    assert namespace["MyBucketLocalProperties"].__annotations__ == {
        "bucket_arn": str,
        "bucket_name": str,
    }


def test_local_execute_uses_custom_link_properties_without_persisting_values(
    phase_app, local_pipeline
):
    StelvioApp.set_user_link_for(
        Bucket,
        lambda bucket: LinkConfig(
            properties={"credential": pulumi.Output.secret("private-value")}
        ),
    )
    StelvioApp.set_user_link_for(Topic, lambda topic: LinkConfig(properties={}))

    @phase_app.run
    def define():
        Bucket("my-bucket")
        Topic("omitted")

    received = []
    phase_app.local_execute(received.append)
    local_pipeline.commands.run_deploy("test")
    assert asdict(received[0]) == {"my_bucket": {"credential": "private-value"}}
    assert (local_pipeline.root / "stlv_local.py").read_text() == (
        "# Generated by Stelvio. Do not edit.\n"
        "from dataclasses import dataclass\n\n\n"
        "@dataclass(frozen=True, slots=True, kw_only=True)\n"
        "class MyBucketLocalProperties:\n"
        "    credential: str\n\n\n"
        "@dataclass(frozen=True, slots=True, kw_only=True)\n"
        "class LocalComponents:\n"
        "    my_bucket: MyBucketLocalProperties\n"
    )
    assert not any(b"private-value" in data for data in local_pipeline.home.files.values())


@mark.parametrize("policy", ["fail", "continue"])
def test_local_callback_error_policy_preserves_deployment(
    phase_app, local_pipeline, policy, capsys
):
    phase_app.run(lambda: None)
    original = ValueError("callback failed")
    order = []
    errors = []

    @phase_app.local_execute(errors=policy)
    def broken(components):
        order.append("broken")
        raise original

    @phase_app.local_execute
    def following(components):
        order.append("following")

    phase_app.on(signals.on_error)(errors.append)
    if policy == "fail":
        with raises(ValueError, match="callback failed") as raised:
            local_pipeline.commands.run_deploy("test")
        assert raised.value is original
        assert order == ["broken"]
        assert len(errors) == 1
        assert errors[0].phase == "local_execute"
        assert errors[0].handler.endswith("broken")
    else:
        local_pipeline.commands.run_deploy("test")
        assert order == ["broken", "following"]
        assert errors == []
        assert capsys.readouterr().err.endswith("ValueError: callback failed\n")
    assert local_pipeline.home.file_exists("state/demo/test.json")
    assert not local_pipeline.home.file_exists("lock/demo/test.json")
    assert list((local_pipeline.root / "work").iterdir()) == []


@mark.parametrize("failure", ["provision", "state_save", "cleanup", "cancel"])
def test_local_execute_is_suppressed_on_failure_or_cancellation(
    phase_app, local_pipeline, monkeypatch, failure
):
    phase_app.run(lambda: None)
    callback = Mock()
    phase_app.local_execute(callback)
    error = KeyboardInterrupt() if failure == "cancel" else ValueError(failure)
    if failure in ("provision", "cancel"):
        monkeypatch.setattr(PulumiStack, "up", Mock(side_effect=error))
    elif failure == "state_save":
        write = local_pipeline.home.write_file

        def fail_state(key, path):
            if key == "state/demo/test.json":
                raise error
            write(key, path)

        monkeypatch.setattr(local_pipeline.home, "write_file", fail_state)
    else:
        monkeypatch.setattr("stelvio.command_run.shutil.rmtree", Mock(side_effect=error))
    with raises(type(error), match="" if failure == "cancel" else failure):
        local_pipeline.commands.run_deploy("test")
    callback.assert_not_called()
    assert not local_pipeline.home.file_exists("lock/demo/test.json")


